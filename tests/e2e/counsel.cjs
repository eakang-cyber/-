// 고민상담소 흐름 E2E: 랜딩 고민 입력 → 생년월일 입력 → 상담지 → 반응 → 심층 상담(데모 결제) → 결정 리포트
const { chromium } = require('playwright');
const BASE = process.env.BASE_URL || 'http://localhost:3000';
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m);
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await p.goto(BASE + '/'); await p.waitForTimeout(1200);
  await p.fill('#landing-worry', '대전 신탄진에 공장 부지를 사려고 하는데, 지금 움직여도 될지 모르겠어요.');
  await p.getByRole('button', { name: /생년월일 넣고 상담지 받기/ }).click();
  await p.fill('#ob-name', '테스터'); await p.getByRole('button', { name: '다음' }).click();
  await p.getByLabel('연도').fill('1988'); await p.getByLabel('월').fill('11'); await p.getByLabel('일').fill('3');
  await p.getByRole('button', { name: '다음' }).click();
  await p.fill('#ob-time', '14:20'); await p.getByRole('button', { name: '다음' }).click();
  await p.selectOption('#ob-city', 'daejeon'); await p.getByRole('button', { name: '다음' }).click();
  await p.getByRole('radio', { name: '남성' }).click(); await p.getByRole('button', { name: '다음' }).click();
  await p.getByRole('button', { name: '내 인생 탐험 시작' }).click(); await p.waitForTimeout(400);
  ok(p.url().endsWith('#ask'), 'onboarding returns to #ask');
  ok((await p.inputValue('#cs-text')).includes('신탄진'), 'worry text carried over');
  ok(await p.getByRole('radio', { name: '부동산·사업장' }).getAttribute('aria-checked') === 'true', 'topic auto-detected');
  await p.getByRole('radio', { name: '3개월 안' }).click();
  await p.getByRole('radio', { name: '두렵다' }).click();
  await p.getByRole('radio', { name: '돈', exact: true }).click();
  await p.getByRole('button', { name: '상담지 받기' }).click(); await p.waitForTimeout(400);
  ok(await p.getByText('이렇게 이해했어요').isVisible(), 'answer sheet shown');
  ok(await p.getByText(/“대전 신탄진에 공장 부지/).isVisible(), 'answer quotes user words');
  ok(await p.getByText('이 고민 앞의 나').isVisible() && await p.getByText('시기의 흐름').isVisible(), 'tradition sections');
  ok(await p.getByRole('link', { name: /토지이음에서 확인/ }).isVisible(), 'reality checklist with official link');
  await p.getByRole('button', { name: '일부만 맞아요' }).click();
  ok(await p.getByText('아카이브의 \'질문\'에 남겼습니다').isVisible(), 'reaction saved to archive');
  await p.getByText('전통 해석은 참고용이며 투자·법률·의료').click();
  await p.getByRole('button', { name: /모의 결제 \(데모\)/ }).click(); await p.waitForTimeout(1200);
  ok(await p.getByText('AI 상담사 풀이').isVisible(), 'deep counsel unlocked');
  ok(await p.getByText(/AI 상담사를 쓸 수 없어요/).isVisible(), 'AI absent outside claude.ai → graceful notice');
  await p.getByRole('button', { name: /24개월 단계별로 정리하기/ }).click(); await p.waitForTimeout(400);
  ok(p.url().endsWith('#decide'), 'to decision report');
  ok(await p.getByText('24개월 단계별 흐름').isVisible(), 'roadmap visible (unlocked)');
  ok(await p.getByText(/앞으로 12개월 중 \d+개월이/).isVisible(), 'phase alignment headline');
  await p.goto(BASE + '/#feedback'); await p.waitForTimeout(300);
  await p.getByRole('radio', { name: '5 아주 좋음' }).click();
  await p.getByRole('radio', { name: '바로 결제할 것 같다' }).click();
  await p.getByRole('radio', { name: '19,900원' }).last().click();
  await p.getByRole('button', { name: '의견 정리하기' }).click();
  await p.getByRole('button', { name: '글로 보기' }).click();
  const fb = await p.getByLabel('의견 요약').inputValue();
  ok(/심층 상담 표시 가격: (19,900|29,000|39,000)원 \/ 모의 결제 누름: 예/.test(fb) && fb.includes('상담지 반응: 일부만 맞아요') && !fb.includes('신탄진'), 'feedback has price test + reaction, no worry text');
  console.log('errors', JSON.stringify(errs));
  await b.close();
})().catch(e => { console.log('CRASH', e.message); process.exit(1); });
